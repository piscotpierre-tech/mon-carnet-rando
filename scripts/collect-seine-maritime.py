"""Retain all 291 official pedestrian PDESI geometries, without inventing GPXs.

The original GeoJSON remains linked. A GPX export of each validated geometry
will be generated by the build and explicitly presented as an export.
"""
import gzip
import hashlib
import importlib
import json
import math
from pathlib import Path
import re
import sys
import urllib.parse

ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT/'scripts'))
source=importlib.import_module('collect-normandie')
prepare=importlib.import_module('prepare-catalogue')
ENDPOINT='https://services-eu1.arcgis.com/Nt9PzCzX9tz2k5Lq/arcgis/rest/services/Itineraires_randonnees_pedestres_PDESI_CD76_janvier_2025/FeatureServer/0/query'
DATASET='https://www.opendata76.fr/datasets/seine-maritime::itineraires-randonnees-pedestres-pdesi-cd76-janvier-2025'
URL=ENDPOINT+'?where=1%3D1&outFields=*&outSR=4326&f=geojson'


def collect():
    raw=source.get(URL);data=json.loads(raw)
    assert len(data['features'])==291 and not data.get('exceededTransferLimit')
    records=[];excluded=[]
    for feature in data['features']:
        attrs=feature['properties'];identifier=attrs['OBJECTID']
        if str(attrs['Pedestre']).lower().strip()!='oui':
            excluded.append({'sourceFeatureId':identifier,'name':attrs['Nom_iti'],'reason':'La fiche n’est pas marquée pédestre dans la source.'})
            continue
        r={'sourceId':f'CD76-PDESI-2025-{identifier}',
           'name':re.sub(r'^\s*\d+\s*[-.)]\s*','',attrs['Nom_iti']),
           'town':'Seine-Maritime','department':'76','km':None,'official':DATASET,
           'gpxSource':None,'sourceFormat':'GeoJSON','sourceEdition':'PDESI de janvier 2025',
           'sourceTraceUrl':ENDPOINT+'?'+urllib.parse.urlencode({'where':f'OBJECTID={identifier}','outFields':'*','outSR':'4326','f':'geojson'}),
           'sourceDatasetUrl':URL,'sourceDatasetSha256':hashlib.sha256(raw.encode()).hexdigest(),
           'sourceFeatureId':identifier}
        try:
            geo=feature['geometry']
            assert geo['type'] in ['LineString','MultiLineString']
            segments=[geo['coordinates']] if geo['type']=='LineString' else geo['coordinates']
            assert all(len(s)>1 for s in segments) and sum(map(len,segments))>5
            assert all(len(p)>=2 and all(math.isfinite(v) for v in p) and -6<p[0]<10 and 42<p[1]<52 for s in segments for p in s)
            length=sum(prepare.distance(a,b) for s in segments for a,b in zip(s,s[1:]))/1000
            assert .1<=length<=1200
            r.update(status='trace-verifiee',segments=segments,pointCount=sum(map(len,segments)),geometryKm=round(length,3),officialLocation=segments[0][0][:2])
        except Exception as error:r.update(status='trace-inexploitable',issue=str(error))
        records.append(r)
    target=ROOT/'catalogue/inventaire-complementaire.json'
    inventory=json.loads(target.read_text())
    inventory['records']=[r for r in inventory['records'] if not r['sourceId'].startswith('CD76-')]+[{k:v for k,v in r.items() if k!='segments'} for r in records]
    inventory['sources']=[s for s in inventory['sources'] if s['department']!='76']+[{'department':'76','source':DATASET,'api':URL,'total':len(records),'announcedTotal':291,'collectedAll':True,'sameSitId':0,'excludedOtherPractices':excluded,'note':'Édition intitulée janvier 2025 : 291 lignes reçues, dont 267 marquées pédestres et 24 autres pratiques exclues. GPX du carnet exporté du GeoJSON officiel.'}]
    target.write_text(json.dumps(inventory,ensure_ascii=False,indent=2)+'\n')
    (ROOT/'catalogue/snapshots/cd76.json.gz').write_bytes(gzip.compress(json.dumps(records,ensure_ascii=False,separators=(',',':')).encode(),mtime=0))
    print(f'{len(records)} géométries officielles CD76 inventoriées',flush=True)


if __name__=='__main__':collect()
